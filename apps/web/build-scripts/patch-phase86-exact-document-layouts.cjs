'use strict';
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const webRoot=fs.existsSync(path.join(root,'apps','web','index.html'))?path.join(root,'apps','web'):root;
const htmlPath=path.join(webRoot,'index.html');
const jsPath=path.join(webRoot,'phase86-exact-document-layouts.js');
const start='<!-- SG_PHASE86_EXACT_DOCUMENT_LAYOUTS_PATCH_START -->';
const end='<!-- SG_PHASE86_EXACT_DOCUMENT_LAYOUTS_PATCH_END -->';
const esc=v=>v.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');
if(!fs.existsSync(htmlPath))throw new Error('Mungon index.html për Phase 8.6: '+htmlPath);
if(!fs.existsSync(jsPath))throw new Error('Mungon phase86-exact-document-layouts.js: '+jsPath);
let html=fs.readFileSync(htmlPath,'utf8');
const js=fs.readFileSync(jsPath,'utf8');
new Function(js);
html=html.replace(new RegExp(esc(start)+'[\\s\\S]*?'+esc(end)+'\\s*','g'),'');
const close=/<\/body>\s*<\/html>\s*$/i;
if(!close.test(html))throw new Error('Mungon mbyllja finale e HTML.');
html=html.replace(close,start+'\n<script id="sg-phase86-exact-document-layouts">\n'+js+'\n</script>\n'+end+'\n</body>\n</html>');
fs.writeFileSync(htmlPath,html);
const check=fs.readFileSync(htmlPath,'utf8');
if((check.match(/SG_PHASE86_EXACT_DOCUMENT_LAYOUTS_PATCH_START/g)||[]).length!==1)throw new Error('Patch-i Phase 8.6 nuk është idempotent.');
['SG_PHASE86_EXACT_DOCUMENT_LAYOUTS_START','sg86-warehouse','sg86-mandate','sg86-invoice','warehouseRows','invoiceRows'].forEach(m=>{if(!check.includes(m))throw new Error('Mungon '+m);});
console.log('Phase 8.6 exact document layouts injected.');
