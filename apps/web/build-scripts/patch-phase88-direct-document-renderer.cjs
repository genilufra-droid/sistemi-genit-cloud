'use strict';
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const webRoot=fs.existsSync(path.join(root,'apps','web','index.html'))?path.join(root,'apps','web'):root;
const htmlPath=path.join(webRoot,'index.html');
const jsPath=path.join(webRoot,'phase88-direct-document-renderer.js');
const start='<!-- SG_PHASE88_DIRECT_DOCUMENT_RENDERER_PATCH_START -->';
const end='<!-- SG_PHASE88_DIRECT_DOCUMENT_RENDERER_PATCH_END -->';
const esc=v=>v.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');
if(!fs.existsSync(htmlPath)||!fs.existsSync(jsPath))throw new Error('Mungojnë skedarët Phase 8.8');
let html=fs.readFileSync(htmlPath,'utf8');
const js=fs.readFileSync(jsPath,'utf8');
new Function(js);
html=html.replace(new RegExp(esc(start)+'[\\s\\S]*?'+esc(end)+'\\s*','g'),'');
const close=/<\/body>\s*<\/html>\s*$/i;
if(!close.test(html))throw new Error('Mungon mbyllja finale e HTML.');
html=html.replace(close,start+'\n<script id="sg-phase88-direct-document-renderer">\n'+js+'\n</script>\n'+end+'\n</body>\n</html>');
fs.writeFileSync(htmlPath,html);
if(!fs.readFileSync(htmlPath,'utf8').includes('SG_PHASE88_DIRECT_DOCUMENT_RENDERER_START'))throw new Error('Phase 8.8 nuk u injektua.');
console.log('Phase 8.8 direct document renderer injected.');