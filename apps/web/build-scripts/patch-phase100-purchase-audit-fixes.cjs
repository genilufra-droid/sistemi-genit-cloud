'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = process.cwd();
const indexPath = path.join(root, 'index.html');
const sourcePath = path.join(root, 'phase100-purchase-audit-fixes.js');
const productJsPath = path.join(root, 'product-odoo-editor.js');
const productCssPath = path.join(root, 'product-odoo-editor.css');
const productActionsJsPath = path.join(root, 'products-erp-actions.js');
const productActionsCssPath = path.join(root, 'products-erp-actions.css');
const productImportJsPath = path.join(root, 'products-odoo-import.js');
const productListActionsJsPath = path.join(root, 'product-list-odoo-actions.js');
const marker = 'SG_PHASE100_PURCHASE_AUDIT_FIXES_START';
const productMarker = 'SG_PRODUCT_ODOO_EDITOR_START';
const productActionsMarker = 'SG_PRODUCTS_ERP_ACTIONS_START';
const productImportMarker = 'SG_PRODUCTS_ODOO_IMPORT_START';
const productListActionsMarker = 'SG_PRODUCT_LIST_ODOO_ACTIONS_START';
if (!fs.existsSync(indexPath)) throw new Error('Mungon index.html');
if (!fs.existsSync(sourcePath)) throw new Error('Mungon phase100-purchase-audit-fixes.js');
if (!fs.existsSync(productJsPath)) throw new Error('Mungon product-odoo-editor.js');
if (!fs.existsSync(productCssPath)) throw new Error('Mungon product-odoo-editor.css');
if (!fs.existsSync(productActionsJsPath)) throw new Error('Mungon products-erp-actions.js');
if (!fs.existsSync(productActionsCssPath)) throw new Error('Mungon products-erp-actions.css');
if (!fs.existsSync(productImportJsPath)) throw new Error('Mungon products-odoo-import.js');
if (!fs.existsSync(productListActionsJsPath)) throw new Error('Mungon product-list-odoo-actions.js');
let html = fs.readFileSync(indexPath, 'utf8');
const source = fs.readFileSync(sourcePath, 'utf8');
const productJs = fs.readFileSync(productJsPath, 'utf8');
const productCss = fs.readFileSync(productCssPath, 'utf8');
const productActionsJs = fs.readFileSync(productActionsJsPath, 'utf8');
const productActionsCss = fs.readFileSync(productActionsCssPath, 'utf8');
const productImportJs = fs.readFileSync(productImportJsPath, 'utf8');
const productListActionsJs = fs.readFileSync(productListActionsJsPath, 'utf8');
html = html.replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi, (block) => (block.includes(marker) || block.includes(productMarker) || block.includes(productActionsMarker) || block.includes(productImportMarker) || block.includes(productListActionsMarker)) ? '' : block);
html = html.replace(/<style\b[^>]*>[\s\S]*?<\/style>/gi, (block) => (block.includes('SG_PRODUCT_ODOO_EDITOR_CSS') || block.includes('SG_PRODUCTS_ERP_ACTIONS_CSS')) ? '' : block);
html += '\n<style>\n' + productCss + '\n' + productActionsCss + '\n</style>\n';
html += '\n<script>\n' + source + '\n</script>\n';
html += '\n<script>\n' + productJs + '\n</script>\n';
html += '\n<script>\n' + productActionsJs + '\n</script>\n';
html += '\n<script>\n' + productImportJs + '\n</script>\n';
html += '\n<script>\n' + productListActionsJs + '\n</script>\n';
if (!html.includes(marker)) throw new Error('Phase 10.0 nuk u injektua');
if (!html.includes(productMarker)) throw new Error('Formulari Odoo i Artikullit nuk u injektua');
if (!html.includes(productActionsMarker)) throw new Error('Veprimet ERP të Artikujve nuk u injektuan');
if (!html.includes(productImportMarker)) throw new Error('Importi Odoo i Artikujve nuk u injektua');
if (!html.includes(productListActionsMarker)) throw new Error('Veprimet Odoo të listës së Artikujve nuk u injektuan');
fs.writeFileSync(indexPath, html);
