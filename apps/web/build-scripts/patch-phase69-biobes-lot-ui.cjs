'use strict';
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const htmlPath=path.join(root,'apps','web','index.html');
const jsPath=path.join(root,'apps','web','phase69-biobes-lot-ui.js');
const start='<!-- SG_PHASE69_BIOBES_LOT_UI_PATCH_START -->';
const end='<!-- SG_PHASE69_BIOBES_LOT_UI_PATCH_END -->';
const esc=(v)=>v.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');
let html=fs.readFileSync(htmlPath,'utf8');
const js=fs.readFileSync(jsPath,'utf8');
html=html.replace(new RegExp(esc(start)+'[\\s\\S]*?'+esc(end)+'\\s*','g'),'');
const closing=/<\/body>\s*<\/html>\s*$/i;
if(!closing.test(html))throw new Error('Mungon mbyllja finale e HTML.');
html=html.replace(closing,start+'\n<script id="sg-phase69-biobes-lot-ui">\n'+js+'\n</script>\n'+end+'\n</body>\n</html>');
fs.writeFileSync(htmlPath,html);
const check=fs.readFileSync(htmlPath,'utf8');
if((check.match(/SG_PHASE69_BIOBES_LOT_UI_PATCH_START/g)||[]).length!==1)throw new Error('Patch-i BioBes nuk është idempotent.');
['SG_PHASE69_BIOBES_LOT_UI_START','Periudha e vjeljes','Kodi i origjinës BioBes','105 — Ferra'].forEach((marker)=>{if(!check.includes(marker))throw new Error('Mungon '+marker);});
console.log('BioBes lot UI injected.');
