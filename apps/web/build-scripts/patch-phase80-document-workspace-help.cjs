'use strict';
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const htmlPath=path.join(root,'apps','web','index.html');
const jsPath=path.join(root,'apps','web','phase80-document-workspace-help.js');
const start='<!-- SG_PHASE80_DOCUMENT_WORKSPACE_HELP_PATCH_START -->';
const end='<!-- SG_PHASE80_DOCUMENT_WORKSPACE_HELP_PATCH_END -->';
const esc=(value)=>value.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');
let html=fs.readFileSync(htmlPath,'utf8');
const js=fs.readFileSync(jsPath,'utf8');
new Function(js);
html=html.replace(new RegExp(esc(start)+'[\\s\\S]*?'+esc(end)+'\\s*','g'),'');
const close=/<\/body>\s*<\/html>\s*$/i;
if(!close.test(html))throw new Error('Mungon mbyllja finale e HTML.');
html=html.replace(close,start+'\n<script id="sg-phase80-document-workspace-help">\n'+js+'\n</script>\n'+end+'\n</body>\n</html>');
fs.writeFileSync(htmlPath,html);
const check=fs.readFileSync(htmlPath,'utf8');
if((check.match(/SG_PHASE80_DOCUMENT_WORKSPACE_HELP_PATCH_START/g)||[]).length!==1)throw new Error('Patch-i Phase 8.0 nuk është idempotent.');
['SG_PHASE80_DOCUMENT_WORKSPACE_HELP_START','sg80OpenHelp','sg80OpenFullManual','Dokumenti real A4','Print / PDF','sg80-tabs'].forEach((marker)=>{if(!check.includes(marker))throw new Error('Mungon '+marker);});
console.log('Phase 8.0 document workspace and contextual help injected.');
