'use strict';
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const htmlPath=path.join(root,'apps','web','index.html');
const jsPath=path.join(root,'apps','web','phase84-electronic-archive.js');
const start='<!-- SG_PHASE84_ELECTRONIC_ARCHIVE_PATCH_START -->';
const end='<!-- SG_PHASE84_ELECTRONIC_ARCHIVE_PATCH_END -->';
const esc=v=>v.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');
let html=fs.readFileSync(htmlPath,'utf8');
const js=fs.readFileSync(jsPath,'utf8');
new Function(js);
html=html.replace(new RegExp(esc(start)+'[\\s\\S]*?'+esc(end)+'\\s*','g'),'');
const close=/<\/body>\s*<\/html>\s*$/i;
if(!close.test(html))throw new Error('Mungon mbyllja finale e HTML.');
html=html.replace(close,start+'\n<script id="sg-phase84-electronic-archive">\n'+js+'\n</script>\n'+end+'\n</body>\n</html>');
fs.writeFileSync(htmlPath,html);
const check=fs.readFileSync(htmlPath,'utf8');
if((check.match(/SG_PHASE84_ELECTRONIC_ARCHIVE_PATCH_START/g)||[]).length!==1)throw new Error('Patch-i Phase 8.4 nuk është idempotent.');
['SG_PHASE84_ELECTRONIC_ARCHIVE_START','Arkiva elektronike','Bashkëngjit skedar','application/pdf'].forEach(m=>{if(!check.includes(m))throw new Error('Mungon '+m);});
console.log('Phase 8.4 electronic archive injected.');