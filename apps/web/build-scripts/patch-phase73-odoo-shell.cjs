'use strict';
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const htmlPath=path.join(root,'apps','web','index.html');
const jsPath=path.join(root,'apps','web','phase73-odoo-shell.js');
const start='<!-- SG_PHASE73_ODOO_SHELL_PATCH_START -->';
const end='<!-- SG_PHASE73_ODOO_SHELL_PATCH_END -->';
const esc=(value)=>value.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');
let html=fs.readFileSync(htmlPath,'utf8');
const js=fs.readFileSync(jsPath,'utf8');
new Function(js);
html=html.replace(new RegExp(esc(start)+'[\\s\\S]*?'+esc(end)+'\\s*','g'),'');
const close=/<\/body>\s*<\/html>\s*$/i;
if(!close.test(html))throw new Error('Mungon mbyllja finale e HTML.');
html=html.replace(close,start+'\n<script id="sg-phase73-odoo-shell">\n'+js+'\n</script>\n'+end+'\n</body>\n</html>');
fs.writeFileSync(htmlPath,html);
const check=fs.readFileSync(htmlPath,'utf8');
if((check.match(/SG_PHASE73_ODOO_SHELL_PATCH_START/g)||[]).length!==1)throw new Error('Patch-i Odoo Shell nuk është idempotent.');
['SG_PHASE73_ODOO_SHELL_START','Kërko module, dokumente, artikuj','mrpDashboard','sg73-native-select','installNumericStabilizer'].forEach((marker)=>{if(!check.includes(marker))throw new Error('Mungon '+marker);});
const phase72=check.lastIndexOf('SG_PHASE72_ODOO_DOCUMENT_LINKS_UI_START');
const phase73=check.lastIndexOf('SG_PHASE73_ODOO_SHELL_START');
if(phase73<phase72)throw new Error('Odoo Shell duhet të injektohet pas Manufacturing dhe linkeve të dokumenteve.');
console.log('Phase 7.3 final Odoo shell injected.');
