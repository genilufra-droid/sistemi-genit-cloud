'use strict';
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const htmlPath=path.join(root,'apps','web','index.html');
const jsPath=path.join(root,'apps','web','phase75-odoo-inventory-ui.js');
const start='<!-- SG_PHASE75_ODOO_INVENTORY_UI_PATCH_START -->';
const end='<!-- SG_PHASE75_ODOO_INVENTORY_UI_PATCH_END -->';
const esc=(value)=>value.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');
let html=fs.readFileSync(htmlPath,'utf8');
const js=fs.readFileSync(jsPath,'utf8');
new Function(js);
html=html.replace(new RegExp(esc(start)+'[\\s\\S]*?'+esc(end)+'\\s*','g'),'');
const close=/<\/body>\s*<\/html>\s*$/i;
if(!close.test(html))throw new Error('Mungon mbyllja finale e HTML.');
html=html.replace(close,start+'\n<script id="sg-phase75-odoo-inventory-ui">\n'+js+'\n</script>\n'+end+'\n</body>\n</html>');
fs.writeFileSync(htmlPath,html);
const check=fs.readFileSync(htmlPath,'utf8');
if((check.match(/SG_PHASE75_ODOO_INVENTORY_UI_PATCH_START/g)||[]).length!==1)throw new Error('Patch-i Inventory nuk është idempotent.');
['SG_PHASE75_ODOO_INVENTORY_UI_START','Paneli Inventory','Transferime të Brendshme','Rregullime Inventari','Raportet Inventory','searchControl','quickCreate'].forEach((marker)=>{if(!check.includes(marker))throw new Error('Mungon '+marker);});
console.log('Phase 7.5 Odoo Inventory UI injected.');
