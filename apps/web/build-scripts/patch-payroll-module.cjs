'use strict';
const fs = require('fs');
const path = require('path');
const root = process.cwd();
const htmlPath = path.join(root, 'index.html');
const js = fs.readFileSync(path.join(root, 'payroll-ui.js'), 'utf8');
const css = fs.readFileSync(path.join(root, 'phase-payroll.css'), 'utf8');
const start = '<!-- SG_PAYROLL_MODULE_START -->';
const end = '<!-- SG_PAYROLL_MODULE_END -->';
let html = fs.readFileSync(htmlPath, 'utf8');
const esc = (x) => x.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
html = html.replace(new RegExp(esc(start) + '[\\s\\S]*?' + esc(end) + '\\s*', 'g'), '');
const bodyClose = html.toLowerCase().lastIndexOf('</body>');
if (bodyClose < 0) throw new Error('Mungon mbyllja finale e HTML.');
const block = start + '\n<style id="sg-payroll-style">\n' + css + '\n</style>\n<script id="sg-payroll-script">\n' + js + '\n</script>\n' + end + '\n';
html = html.slice(0, bodyClose) + block + html.slice(bodyClose);
fs.writeFileSync(htmlPath, html);
const check = fs.readFileSync(htmlPath, 'utf8');
if ((check.match(/SG_PAYROLL_MODULE_START/g) || []).length !== 1) throw new Error('Moduli i pagave nuk është idempotent.');
['Lista e Pagave', 'Punonjësit', 'Parametrat e Pagave', 'sgPayrollExport', 'Paga e tatueshme'].forEach((m) => { if (!check.includes(m)) throw new Error('Mungon ' + m + ' në modulin e pagave.'); });
console.log('Payroll module patched.');
